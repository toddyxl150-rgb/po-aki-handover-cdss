#!/usr/bin/env python
"""Zero-residue scanner for the public release folder.

Three independent gates, all of which must pass before a push:

  A. File-type gate
     No parquet / npy / csv.gz / cohort_*.csv / vitals_*.csv / oof_*.csv / *.bak*
     anywhere in the tree.  These are the containers that hold row-level rows.

  B. Row-level identifier gate
     Every shipped tabular file is inspected for identifier *columns*
     (patient_id, subject_id, case_id, stay_id, hadm_id, icustay_id, ...) and,
     for text/CSV files, for long digit strings that look like record keys.
     Aggregate tables (one row per model / characteristic / comparison) pass;
     anything with one row per patient fails.

  C. Hard-coded host path gate
     No `E:\\`, `C:\\`, `/home/<user>`, `/Users/<user>`, or a bare Windows
     user name in any source or config file.  Database roots must come from
     CLI flags or environment variables.

Exit code 0 = clean, 1 = at least one violation.  Intended to run in CI and
before `git push`.

    python tools/check_no_phi.py                 # scan this folder
    python tools/check_no_phi.py --root <dir>    # scan another checkout
"""
from __future__ import annotations

import argparse
import gzip
import io
import re
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Tuple

SKIP_DIRS = {".git", "__pycache__", ".ipynb_checkpoints", "demo_run", "node_modules"}
# Generated by demo/run_demo.py, git-ignored, and by construction 100 % synthetic.
# They are skipped so that running the demo does not turn this gate red.
SKIP_PREFIX = ("demo/data/",)

# ---- A. containers that may hold row-level records -------------------------
FORBIDDEN_SUFFIX = (".parquet", ".npy", ".npz", ".csv.gz", ".feather", ".pkl", ".h5")
FORBIDDEN_GLOB = ("cohort_*.csv", "vitals_*.csv", "oof_*.csv", "*.bak", "*.bak_*",
                  "windows_*.npy", "features_*.parquet", "*.vital", "*.edf")

# ---- B. identifier columns --------------------------------------------------
ID_COLUMNS = {"patient_id", "patientid", "patient_unit_stay_id", "patientunitstayid",
              "subject_id", "subjectid", "uniquepid", "case_id", "caseid",
              "stay_id", "stayid", "icustay_id", "hadm_id", "admissionid",
              "encounter_id", "mrn", "ssn"}

TEXT_SUFFIX = (".py", ".md", ".txt", ".yaml", ".yml", ".json", ".csv", ".cfg", ".toml",
               ".ini", ".sh", ".gitignore", ".license")

# ---- C. host path patterns --------------------------------------------------
ABS_PATH = [
    (re.compile(r"[A-Za-z]:[\\/](?:Medical_project|Users|Data|Projects|Work|Desktop)"), "Windows absolute path"),
    (re.compile(r"[A-Za-z]:\\\\"), "escaped Windows absolute path"),
    (re.compile(r"/(?:home|Users)/[A-Za-z0-9._-]+/"), "POSIX home path"),
    (re.compile(r"Administrator|C:\\\\Users", re.I), "local user name"),
]
# Paths that are legitimately part of a public contract (docs placeholders).
ABS_PATH_ALLOW = ("data/eicu", "data/inspire", "data/vitaldb")

DIGIT_RUN = re.compile(r"(?<![\d.])\d{7,}(?![\d.])")
MAX_ROWS_WITH_IDS = 0          # any data file that has an ID column is a violation


def _iter_files(root: Path) -> Iterable[Path]:
    for p in sorted(root.rglob("*")):
        if p.is_dir():
            continue
        if any(part in SKIP_DIRS for part in p.parts):
            continue
        if p.relative_to(root).as_posix().startswith(SKIP_PREFIX):
            continue
        yield p


def _read_text(p: Path) -> str:
    try:
        if p.suffix == ".gz":
            with gzip.open(p, "rt", encoding="utf-8", errors="replace") as f:
                return f.read(2_000_000)
        return p.read_text(encoding="utf-8", errors="replace")
    except Exception:  # noqa: BLE001
        return ""


def check_types(root: Path) -> List[str]:
    bad: List[str] = []
    for p in _iter_files(root):
        rel = p.relative_to(root).as_posix()
        if p.name.endswith(FORBIDDEN_SUFFIX):
            bad.append(f"[A] forbidden container: {rel}")
            continue
        for g in FORBIDDEN_GLOB:
            if p.match(g):
                bad.append(f"[A] forbidden file pattern '{g}': {rel}")
                break
    return bad


def check_ids(root: Path) -> List[str]:
    bad: List[str] = []
    for p in _iter_files(root):
        rel = p.relative_to(root).as_posix()
        if p.suffix not in (".csv", ".tsv", ".json", ".md", ".txt"):
            continue
        if p.suffix in (".md", ".txt"):
            continue          # prose may legitimately name the schema keys
        text = _read_text(p)
        if not text:
            continue
        if p.suffix == ".json":
            if any(f'"{c}"' in text for c in ID_COLUMNS):
                bad.append(f"[B] identifier key in {rel}")
            continue
        header = text.splitlines()[0] if text.splitlines() else ""
        cols = {c.strip().strip('"').lower() for c in header.split(",")}
        hit = sorted(cols & ID_COLUMNS)
        if hit:
            n_rows = max(len(text.splitlines()) - 1, 0)
            bad.append(f"[B] identifier column(s) {hit} in {rel} ({n_rows} data rows)")
        # long digit runs outside the header = row keys or timestamps in epoch form
        body = "\n".join(text.splitlines()[1:200])
        runs = DIGIT_RUN.findall(body)
        if runs:
            bad.append(f"[B] {len(runs)} long digit token(s) in {rel} "
                       f"(e.g. {runs[0]}) — possible record key")
    return bad


def check_paths(root: Path) -> List[str]:
    bad: List[str] = []
    for p in _iter_files(root):
        if p.suffix not in TEXT_SUFFIX and p.name != ".gitignore":
            continue
        rel = p.relative_to(root).as_posix()
        if rel == "tools/check_no_phi.py":
            continue          # this file necessarily contains the patterns it hunts
        for i, line in enumerate(_read_text(p).splitlines(), 1):
            if any(a in line for a in ABS_PATH_ALLOW):
                continue
            for pat, why in ABS_PATH:
                if pat.search(line):
                    bad.append(f"[C] {why} at {rel}:{i}: {line.strip()[:100]}")
                    break
    return bad


def scan(root: Path) -> Tuple[List[str], Dict[str, int]]:
    viol = check_types(root) + check_ids(root) + check_paths(root)
    files = list(_iter_files(root))
    stats = {
        "files": len(files),
        "bytes": sum(f.stat().st_size for f in files),
        "csv": sum(1 for f in files if f.suffix == ".csv"),
        "py": sum(1 for f in files if f.suffix == ".py"),
    }
    return viol, stats


def main() -> int:
    ap = argparse.ArgumentParser(description="公开发布目录的患者数据零残留扫描")
    ap.add_argument("--root", default=".", help="待扫描目录（默认当前目录）")
    args = ap.parse_args()
    root = Path(args.root).resolve()

    viol, st = scan(root)
    print("=" * 74)
    print(f"Patient-data zero-residue scan: {root}")
    print("=" * 74)
    print(f"  files {st['files']}  ({st['bytes']/1024:.1f} KiB)   "
          f".py {st['py']}   .csv {st['csv']}")
    print("  gate A  file-type / container ......... "
          f"{'PASS' if not check_types(root) else 'FAIL'}")
    print("  gate B  row-level identifiers ......... "
          f"{'PASS' if not check_ids(root) else 'FAIL'}")
    print("  gate C  hard-coded host paths ......... "
          f"{'PASS' if not check_paths(root) else 'FAIL'}")
    if viol:
        print(f"\n  {len(viol)} violation(s):")
        for v in viol:
            print("   ", v)
        print("\nRESULT: FAIL")
        return 1
    print("\nRESULT: PASS — no patient-level file, identifier column, or host path found.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
